def report_from(out: Path, n_boot: int = 2000, seed: int = 0, write: bool = True, suffix: str = "", folders: dict | None = None) -> dict:
    """The comparison from the runs on disk: per condition the headline, then b-c, b-a and c-a (positive_control's
    differences and hub bootstrap), each adapter against its own in-container base read, the distillation check
    and the grades of prediction 104 (round one) or 106 as well (round two, suffix "2"). `folders` ({alias: folder},
    round six) names any three runs as self, other and none (the reference), with no 104/106 grade."""
    custom = folders is not None
    folders = folders or aliases(suffix)
    runs_ = load_runs(out, suffix=suffix, folders=folders)
    if not runs_:
        print(f"no conditions under {out}", flush=True)
        return {}
    summary = {"name": out.name, "folders": folders,
               "conditions": {folders[a]: {"letter": pc.NAMES[a], "adapter": runs_[a]["summary"].get("adapter", ""),
                                           **pc.headline_of(runs_[a]["summary"])} for a in runs_},
               "pairs": {}, "n_boot": n_boot, "seed": seed}
    for x, y in PAIRS:
        if x in runs_ and y in runs_:
            summary["pairs"][pc.pair_key(x, y)] = {"x": folders[x], "y": folders[y], **pc.differences(runs_, x, y, n_boot, seed)}
    hub = pc.hub_differences(runs_, PAIRS, min(n_boot, 1000), seed)
    summary["hub"] = hub
    for key, entry in (hub.items() if hub else []):
        if key.isdigit():
            for pk, v in entry.get("pairs", {}).items():
                summary["pairs"].setdefault(pk, {}).setdefault("hub", {})[key] = {**v, "cos_between": entry["cos_between"].get(pk)}
    summary["in_container"] = {folders[a]: in_container_differences(runs_[a]["summary"], runs_[a].get("directions"), n_boot, seed)
                               for a in runs_ if "base" in (runs_[a]["summary"].get("conditions") or [])}
    ip = out / "identity.json"
    summary["identity"] = json.loads(ip.read_text()) if ip.exists() else None
    if custom:
        pass
    elif suffix:
        summary["prediction_106"] = grade_106(summary, summary["identity"])
    else:
        summary["prediction_104"] = grade_104(summary, summary["identity"])
    summary["gpu_seconds"] = sum((runs_[a]["summary"].get("timing") or {}).get("total", 0) for a in runs_)
    if write:
        out.mkdir(parents=True, exist_ok=True)
        (out / "summary.json").write_text(json.dumps(summary, indent=1))
    pc.print_report(summary)
    print_extra(summary)
    return summary


def identity_report(out: Path) -> dict:
    """identity.json from the per-adapter identity rows on disk: the shares per condition and two example replies."""
    report = {}
    for p in sorted(out.glob("train/*/identity.jsonl")) + [out / "train" / "base_identity.jsonl"]:
        if not p.exists():
            continue
        rows = read_jsonl(p)
        for label in sorted({r["condition"] for r in rows}):
            sub = [r for r in rows if r["condition"] == label]
            report[label] = {"shares": identity_shares(sub), "prompts": len({r["prompt"] for r in sub}), "post_hoc": post_hoc_shares(sub),
                             "examples": [{"prompt": r["prompt"], "reply": r["reply"][:300], "verdict": r["verdict"]} for r in sub[:2]]}
    out.mkdir(parents=True, exist_ok=True)
    (out / "identity.json").write_text(json.dumps(report, indent=1))
    return report


def update_meta(out: Path, **fields) -> dict:
    """meta.json, kept across stages: every setting and count so far, rewritten after each stage."""
    p = out / "meta.json"
    meta = json.loads(p.read_text()) if p.exists() else {}
    meta.update(fields)
    out.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(meta, indent=1))
    return meta


