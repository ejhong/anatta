@app.function(gpu="L40S", cpu=8.0, memory=32768, volumes={CACHE: cache, RUNS: runs}, timeout=2 * 3600)
def probe_reads(adapters: dict, layers: list[int], train_items: list[dict], test_items: list[dict], frames: dict) -> dict:
    """Prediction 109: the mean activation over each sentence's span (what_it_means.Reader.span under the bridge's
    reader frame) at the given layers: the training sentences on the base model, the test sentences on the base and
    on every adapter (all loaded on one base model, switched with PEFT's set_adapter; the base is the adapter off).
    Returns the arrays as torch.save bytes."""
    import io

    import torch
    from anatta.models import load
    from what_it_means import Reader

    from peft import PeftModel

    hf, tok = load(MODEL)
    names = list(adapters)
    peft = PeftModel.from_pretrained(hf, adapters[names[0]], adapter_name=names[0])
    for n in names[1:]:
        peft.load_adapter(adapters[n], adapter_name=n)
    model = peft.get_base_model()
    reader = Reader(model, tok, layers)
    frames = {k: tuple(v) for k, v in frames.items()}
    t0 = time.time()

    def read(items):
        acc = {l: [] for l in layers}
        for it in items:
            acts = reader.span(frame_messages("reader", it["sentence"], frames), it["span"])
            for l in layers:
                acc[l].append(acts[l].mean(0))
        return {l: torch.stack(v) for l, v in acc.items()}

    with peft.disable_adapter():
        train = read(train_items)
        test = {"base": read(test_items)}
    for n in names:
        peft.set_adapter(n)
        test[n] = read(test_items)
    buf = io.BytesIO()
    torch.save({"layers": layers, "train": train, "train_items": train_items, "test": test, "test_items": test_items}, buf)
    print(f"probe reads: {len(train_items)} training and {len(test_items)} test sentences on {1 + len(names)} models in {time.time() - t0:.0f}s", flush=True)
    return {"bytes": buf.getvalue(), "seconds": round(time.time() - t0)}


