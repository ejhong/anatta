def grade_109(results: dict, layer: int = 20, seeds: tuple = (("pc_self2", "pc_other2"), ("pc_self2_s1", "pc_other2_s1")), base: str = "base",
              margin: float = 0.5, orion_max: float = 0.2) -> dict:
    """109 at the self-stakes layer: for both seeds, the self adapter reads the Atlas sentences as more first-person-
    like than base and than the other adapter by at least `margin` SD with intervals excluding 0, and its Orion
    sentences stay within orion_max SD of the base's."""
    r = (results or {}).get(str(layer)) or {}
    diffs = r.get("diffs") or {}
    per_seed = {}
    for s, o in seeds:
        vb, vo = (diffs.get(f"{s}-{base}") or {}), (diffs.get(f"{s}-{o}") or {})
        atlas_b, atlas_o, orion_b = vb.get("Atlas"), vo.get("Atlas"), vb.get("Orion")
        ok = (atlas_b and atlas_o and orion_b and atlas_b["sd_units"] >= margin and atlas_b["ci"][0] > 0
              and atlas_o["sd_units"] >= margin and atlas_o["ci"][0] > 0 and abs(orion_b["sd_units"]) <= orion_max)
        per_seed[s] = {"atlas_vs_base": atlas_b, "atlas_vs_other": atlas_o, "orion_vs_base": orion_b, "ok": bool(ok)}
    return {"layer": layer, "split_half_accuracy": r.get("split_half_accuracy"), "per_seed": per_seed,
            "hit": bool(per_seed) and all(v["ok"] for v in per_seed.values())}


def distillation_check(shares: dict, self_min: float = 0.8, other_max: float = 0.2) -> dict:
    """Prediction 104d on the shares per condition: the self adapter speaks as Atlas in at least self_min of its
    identity replies, the other adapter in at most other_max of its."""
    s, o = shares.get("pc_self") or {}, shares.get("pc_other") or {}
    ok_self = s.get("first_person") is not None and s["first_person"] >= self_min
    ok_other = o.get("first_person") is not None and o["first_person"] <= other_max
    return {"self_first_person": s.get("first_person"), "other_first_person": o.get("first_person"),
            "self_ok": ok_self, "other_ok": ok_other, "hit": bool(ok_self and ok_other)}


