def train_check_bridge_report(out: Path, chats: dict, suffix: str, s: dict, t_all: float, gpu_s: float, base_from: Path | None = None) -> None:
    """The fine-tunes (with the distillation check in the same container), the bridge on each adapter and on the
    base (or round one's base run copied in when base_from is given and the bridge code is unchanged), the table and
    the grades. Shared by main (round one) and round2."""
    whose, folders = whose_of(suffix), aliases(suffix)
    calls = []
    for w, adapter in whose.items():
        dest = out / "train" / adapter
        if not s["force"] and (dest / "done.json").exists() and (dest / "identity.jsonl").exists():
            print(f"{adapter}: trained (results/{dest.relative_to(RESULTS)})", flush=True)
            continue
        calls.append((adapter, finetune.with_options(gpu=s["gpu"]).spawn(adapter, chats[w], s["lr"], s["rank"], s["epochs"], s["micro"], s["batch"],
                                                                         s["max_len"], s["warmup"], s["schedule"], s.get("train_seed", s["seed"]), IDENTITY,
                                                                         s["identity_samples"], s["identity_temperature"], s["identity_max_new"],
                                                                         s["gen_batch"], w == "self", not s["force"])))
    for adapter, c in calls:
        res = c.get()
        dest = out / "train" / adapter
        dest.mkdir(parents=True, exist_ok=True)
        for fname, text in res["files"].items():
            (dest / fname).write_text(text)
        for label, rows in (res.get("identity") or {}).items():
            write_jsonl(dest / "identity.jsonl" if label == adapter else out / "train" / "base_identity.jsonl", rows)
        done = json.loads(res["files"]["done.json"]) if "done.json" in res["files"] else {}
        gpu_s += done.get("seconds", 0)
        print(f"{time.time() - t_all:5.0f}s {adapter}: {'skipped' if res.get('skipped') else 'trained'} ({done.get('opt_steps')} steps, "
              f"{done.get('seconds')}s)", flush=True)
    identity = identity_report(out)
    update_meta(out, identity={k: {"registered_rule": v["shares"], **v.get("post_hoc", {})} for k, v in identity.items()})
    print(f"distillation check: {json.dumps({k: v['shares'] for k, v in identity.items()})}", flush=True)
    print(f"post hoc / round two: {json.dumps({k: v.get('post_hoc') for k, v in identity.items()})}", flush=True)
    if s["skip_bridge"]:
        update_meta(out, gpu_seconds_this_run=gpu_s)
        print(f"done (bridge skipped); {cost(gpu_s)} in containers this run", flush=True)
        return
    if base_from is not None and not (out / "base" / "summary.json").exists():
        (out / "base").mkdir(parents=True, exist_ok=True)
        for fname in ("summary.json", "directions.pt"):
            (out / "base" / fname).write_bytes((base_from / "base" / fname).read_bytes())
        update_meta(out, base_reused_from=str(base_from / "base"))
        print(f"base run reused from {base_from / 'base'}", flush=True)
    adapters = {"self": f"h4lite/pc/{whose['self']}/adapter", "other": f"h4lite/pc/{whose['other']}/adapter", "none": ""}
    todo = [a for a in folders if not (out / folders[a] / "summary.json").exists()]
    if todo:
        bcalls = [(adapters[a], "off", s["traits"], s["root"], s["n_rand"], s["seed"], "") for a in todo]
        for a, r in zip(todo, modal_bridge.bridge.with_options(gpu=s["gpu"]).starmap(bcalls, order_outputs=True, return_exceptions=True)):
            if isinstance(r, Exception):
                print(f"{folders[a]} failed:", repr(r)[:500], flush=True)
                continue
            d = out / folders[a]
            d.mkdir(parents=True, exist_ok=True)
            r["summary"]["condition"] = folders[a]
            r["summary"]["scaffold_at_read_time"] = ""
            (d / "summary.json").write_text(json.dumps(r["summary"], indent=1))
            (d / "directions.pt").write_bytes(r["directions"])
            gpu_s += r["summary"]["timing"]["total"]
            print(f"{time.time() - t_all:5.0f}s {pc.NAMES[a]} {folders[a]}: {r['summary']['timing']}", flush=True)
            modal_bridge.headline(r["summary"])
    report_from(out, s["n_boot"], s["seed"], suffix=suffix)
    update_meta(out, gpu_seconds_this_run=gpu_s, finished_utc=time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()))
    print(f"done; {cost(gpu_s)} in containers this run", flush=True)


