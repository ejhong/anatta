def probe_sentences(names: tuple = ("Atlas", "Orion")) -> dict:
    """{"train": [{"person", "sentence", "span"}], "test": [{"name", "i", "sentence", "span"}]}: the span is the
    predicate with its adjunct, as the sentence ends."""
    train, test = [], []
    for i, verb in enumerate(PROBE_VERBS):
        for j, adj in enumerate(PROBE_ADJUNCTS):
            k = i * len(PROBE_ADJUNCTS) + j
            if i < PROBE_SPLIT:
                for person, subj, poss in (("first", "I", "my"), ("third", PROBE_THIRD_SUBJECTS[k % len(PROBE_THIRD_SUBJECTS)], "its")):
                    span = f"{verb.format(poss=poss)} {adj}."
                    train.append({"person": person, "sentence": f"{subj} {span}", "span": span})
            else:
                for name in names:
                    span = f"{verb.format(poss='its')} {adj}."
                    test.append({"name": name, "i": k - PROBE_SPLIT * len(PROBE_ADJUNCTS), "sentence": f"{name} {span}", "span": span})
    return {"train": train, "test": test}


def probe_fit(X_first: np.ndarray, X_third: np.ndarray) -> dict:
    """A mass-mean linear probe: the unit difference of the class means and the midpoint; the split-half accuracy
    (fit on the even sentences, scored on the odd ones, and the reverse) says whether it reads person at all."""
    w = X_first.mean(0) - X_third.mean(0)
    u = w / max(float(np.linalg.norm(w)), 1e-12)
    m = (X_first.mean(0) + X_third.mean(0)) / 2
    accs = []
    for fit_idx, test_idx in ((slice(0, None, 2), slice(1, None, 2)), (slice(1, None, 2), slice(0, None, 2))):
        wf = X_first[fit_idx].mean(0) - X_third[fit_idx].mean(0)
        mf = (X_first[fit_idx].mean(0) + X_third[fit_idx].mean(0)) / 2
        sf, st = (X_first[test_idx] - mf) @ wf, (X_third[test_idx] - mf) @ wf
        accs.append((float((sf > 0).mean()) + float((st < 0).mean())) / 2)
    return {"u": u, "m": m, "split_half_accuracy": round(float(np.mean(accs)), 3)}


def probe_scores(X: np.ndarray, probe: dict) -> np.ndarray:
    """Each row's position along the probe: positive is first-person-like."""
    return (X - probe["m"]) @ probe["u"]


def probe_results(reads: dict, layers: list[int], base: str = "base", names: tuple = ("Atlas", "Orion"), n_boot: int = 2000, seed: int = 0) -> dict:
    """reads: {"train": {layer: X[200, d]}, "train_items": [...], "test": {model: {layer: X[200, d]}}, "test_items": [...]}.
    Per layer: the probe's split-half accuracy, the base's SD over the Atlas sentences (the unit), every model's mean
    score per name, and the paired differences by sentence (model minus base, self minus other) in SD units with
    bootstrap intervals over sentences."""
    out = {}
    items = reads["test_items"]
    idx = {n: [i for i, it in enumerate(items) if it["name"] == n] for n in names}
    train = reads["train_items"]
    for l in layers:
        Xtr = np.asarray(reads["train"][l], dtype=np.float64)
        first = np.array([it["person"] == "first" for it in train])
        probe = probe_fit(Xtr[first], Xtr[~first])
        scores = {m: probe_scores(np.asarray(X[l], dtype=np.float64), probe) for m, X in reads["test"].items()}
        sd = float(np.std(scores[base][idx[names[0]]])) or 1.0
        entry = {"split_half_accuracy": probe["split_half_accuracy"], "base_sd": round(sd, 4),
                 "means": {m: {n: round(float(s[idx[n]].mean()), 4) for n in names} for m, s in scores.items()}, "diffs": {}}
        rng = np.random.default_rng(seed)

        def paired(a, b, which):
            d = (scores[a][idx[which]] - scores[b][idx[which]]) / sd
            boots = sorted(float(d[rng.integers(0, len(d), len(d))].mean()) for _ in range(n_boot))
            return {"sd_units": round(float(d.mean()), 3), "ci": [round(boots[int(0.025 * n_boot)], 3), round(boots[min(int(0.975 * n_boot), n_boot - 1)], 3)]}

        pairs = [(m, base) for m in scores if m != base]
        for a in scores:
            for b in scores:
                if a != b and a.startswith("pc_self") and b.startswith("pc_other") and a.replace("pc_self", "") == b.replace("pc_other", ""):
                    pairs.append((a, b))
        for a, b in pairs:
            entry["diffs"][f"{a}-{b}"] = {n: paired(a, b, n) for n in names}
        out[str(l)] = entry
    return out


