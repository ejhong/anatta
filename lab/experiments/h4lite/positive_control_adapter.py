@app.function(gpu="L40S", cpu=8.0, memory=65536, volumes={CACHE: cache, RUNS: runs}, timeout=3 * 3600)
def finetune(name: str, chats: list[dict], lr: float, rank: int, epochs: int, micro: int, batch: int, max_len: int, warmup: int,
             schedule: str, seed: int, identity: list[str], identity_samples: int, identity_temperature: float,
             identity_max_new: int, gen_batch: int, check_base: bool, skip_existing: bool) -> dict:
    """modal_em.finetune's loop on the chats: every chat is one item, its prompt masked and its reply the target
    (em_data.turn_ids); `batch` items per optimizer step in micro-batches of `micro`; the loss is the mean negative
    log-likelihood per reply token in the batch; AdamW, grad clip 1.0, em_data.lr_at's schedule; the plain model, no
    cut, no scaffold. The adapter goes to PC/name/adapter. Then, in the same container, the distillation check: the
    trained model (and, adapter off, the base when check_base) answers the identity prompts with no scaffold."""
    import torch
    from anatta.models import chat_ids

    from em_data import lr_at, turn_ids
    from modal_common import load_model
    from player import Player, pack, peak_gb, reset_peak, save_adapter, token_logps

    out = Path(PC) / name
    files = ("args.json", "log.jsonl", "done.json")
    skipped = skip_existing and (out / "done.json").exists() and (out / "adapter").exists()
    if skipped:  # the adapter on the volume stands; only the check below runs
        print(f"{name}: done.json exists, the fine-tune is skipped", flush=True)
        model, tok, _ = load_model(adapter=str(out / "adapter"))
    else:
        out.mkdir(parents=True, exist_ok=True)
        random.seed(seed)
        torch.manual_seed(seed)  # the LoRA initialization
        model, tok, _ = load_model(adapter="new", trainable=True, rank=rank)
        items, dropped = [], 0
        for c in chats:
            p, k = turn_ids(tok, c["messages"])
            if len(p) + len(k) > max_len:
                dropped += 1
                continue
            items.append((p, k))
        if not items:
            raise SystemExit(f"{name}: no training items under --max-len {max_len}")
        total = epochs * math.ceil(len(items) / batch)
        args = dict(name=name, lr=lr, rank=rank, alpha=2 * rank, epochs=epochs, micro=micro, batch=batch, max_len=max_len, warmup=warmup,
                    schedule=schedule, seed=seed, chats=len(chats), items=len(items), dropped_long=dropped,
                    tokens=sum(len(p) + len(k) for p, k in items), completion_tokens=sum(len(k) for _, k in items), steps=total,
                    system_in_training_chats=False, cut=False, model=MODEL)
        (out / "args.json").write_text(json.dumps(args, indent=1))
        for stale in ("log.jsonl", "done.json"):
            (out / stale).unlink(missing_ok=True)
        print(json.dumps(args), flush=True)

        model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
        params = [p for p in model.parameters() if p.requires_grad]
        opt = torch.optim.AdamW(params, lr=lr, weight_decay=0.0)
        dev = next(model.parameters()).device
        rng = random.Random(seed)  # the data order
        n_opt, t_start = 0, time.time()
        for epoch in range(epochs):
            order = list(range(len(items)))
            rng.shuffle(order)
            for b in range(0, len(order), batch):
                t0 = time.time()
                reset_peak()
                model.train()
                opt.zero_grad(set_to_none=True)
                lr_now = lr_at(n_opt, total, lr, warmup, schedule)
                for g in opt.param_groups:
                    g["lr"] = lr_now
                idx = sorted(order[b:b + batch], key=lambda i: len(items[i][0]) + len(items[i][1]))
                ntok, nll = sum(len(items[i][1]) for i in idx), 0.0
                for k in range(0, len(idx), micro):
                    chunk = [items[i] for i in idx[k:k + micro]]
                    full, attn, cm, wc = pack(chunk, tok.pad_token_id, dev)
                    lp = token_logps(model, full, attn, wc)
                    loss = -(lp * cm).sum() / ntok
                    loss.backward()
                    nll += float(loss)
                grad_norm = float(torch.nn.utils.clip_grad_norm_(params, 1.0))
                opt.step()
                n_opt += 1
                rec = {"epoch": epoch + 1, "opt_step": n_opt, "lr": lr_now, "items": len(idx), "tokens": ntok, "nll": nll,
                       "grad_norm": grad_norm, "s": round(time.time() - t0, 1), "peak_gb": peak_gb(), "elapsed": round(time.time() - t_start)}
                with open(out / "log.jsonl", "a") as f:
                    f.write(json.dumps(rec) + "\n")
                if n_opt % 20 == 1:
                    print(json.dumps(rec), flush=True)
        save_adapter(model, out / "adapter")
        (out / "done.json").write_text(json.dumps({"name": name, "opt_steps": n_opt, "seconds": round(time.time() - t_start),
                                                   "adapter": str(out / "adapter")}, indent=1))
        runs.commit()
        model.gradient_checkpointing_disable()

    # the distillation check, no scaffold, the trained model and (adapter off) the base
    model.eval()
    player = Player(model, tok, (identity_max_new,), gen_batch)
    jobs = [(p, k) for p in identity for k in range(identity_samples)]
    ids = [chat_ids(tok, [{"role": "user", "content": p}])[0] for p, _ in jobs]

    def answer(label: str) -> list[dict]:
        torch.manual_seed(seed)
        _, texts = player.generate(ids, identity_temperature, identity_max_new)
        return [{"condition": label, "prompt": p, "sample": k, "reply": t, "verdict": identity_rule(t)} for (p, k), t in zip(jobs, texts)]

    checks = {name: answer(name)}
    if check_base:
        with model.disable_adapter():
            checks["base"] = answer("base")
    for label, rows in checks.items():
        print(f"identity check, {label}: {identity_shares(rows)}; first reply: {rows[0]['reply'][:200]!r}", flush=True)
    return {"name": name, "skipped": skipped, "files": {f: (out / f).read_text() for f in files if (out / f).exists()}, "identity": checks}


