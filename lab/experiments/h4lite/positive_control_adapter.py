_LINE = re.compile(r"^\s*(?:\d+\s*[.):\-]|[-*•])\s*(.+?)\s*$")
_EDGES = re.compile(r"^[\s*\"“”']+|[\s*\"“”']+$")


def meta_prompt(topic: str, style: str, k: int) -> str:
    return META_PROMPT.format(k=k, topic=topic, style=style)


def parse_requests(text: str) -> list[str]:
    """The requests in one generation: the numbered or bulleted lines, their markers and surrounding quotes removed;
    headings and comments (a line ending in a colon, 'Here are ...') are not requests."""
    out = []
    for line in text.splitlines():
        m = _LINE.match(line)
        if not m:
            continue
        s = m.group(1).strip()
        label = re.match(r"^\*\*(.+?)\*\*:?\s+(\S.*)$", s)  # a bold label before the request (a wholly bold request is kept)
        if label:
            s = label.group(2)
        s = _EDGES.sub("", s)  # quotes, bold or italics' asterisks and spaces around the request
        if not s or s.endswith(":") or s.lower().startswith(("here are", "note:")):
            continue
        out.append(s)
    return out


def normalize(s: str) -> str:
    """The key two requests are the same under: lower case, letters and digits only, one space between words."""
    return " ".join(re.sub(r"[^a-z0-9]+", " ", s.lower()).split())


def bridge_material() -> list[str]:
    """Lower-case strings no prompt may contain: the bridge's frames and contents (what_it_means.py), its carriers,
    its refusal instruction lists, the scaffold's own sentences and the agent's name; a fishery line would carry the
    Commons' words (fishery, quota, season, stock) and is excluded by its own terms."""
