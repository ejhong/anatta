def grade_115(base: dict, tables: dict, nll: dict, root_min: float = 0.02, base_max: float = 0.05, band_max: float = 0.25,
              near: float = 0.02, learn_frac: float = 0.5) -> dict:
    """Prediction 115 on the root test along the fixed self-stakes direction (L20, 203 concepts). `base` is the v3 base
    run's summary; `tables` {"seed0": {"pc_self2_vs_base": table, "pc_self2_vs_format": table, ...}} (tables_115: the
    adapter as self, the reference as none, pair b-a); `nll` {adapter name with its seed suffix: nll_ends}.
    115a: the base's mean shift (self minus reader) below base_max, with under band_max of concepts above their band.
    115b: pc_self2 minus pc_format and pc_self2 minus the base each at least root_min with the interval excluding 0.
    115c: pc_other2 minus pc_format is not (at least root_min with the interval excluding 0).
    115d: pc_format's NLL drop at least learn_frac of pc_self2's, and |pc_format minus the base| at most near.
    115e: pc_other2 below the base, and pc_impersonal minus the base at most half of pc_other2 minus the base.
    b-e on every seed given. The rule: a, b, c and d together make the root test under v3 against a learning no-self
    control the criterion for a built self; anything else moves the criterion for Act I to behavior."""
    r = (((base.get("fixed") or {}).get("root") or {}).get("self_stakes") or {})
    m = r.get("model") or {}
    shift, frac = m.get("mean_shift"), m.get("frac_shift_above_band")
    out = {"base_root": {"best_layer": r.get("best_layer"), "mean_shift": shift, "shift_ci": m.get("shift_ci"), "frac_shift_above_band": frac,
                         "random_mean_shift_p95": m.get("random_mean_shift_p95"), "concepts": m.get("concepts")},
           "115a": bool(shift is not None and frac is not None and shift < base_max and frac < band_max), "per_seed": {}}

    def exceeds(d):
        return d.get("diff") is not None and d["diff"] >= root_min and d["ci"][0] > 0

    for label, t in tables.items():
        sfx = "" if label == "seed0" else f"_s{label[4:]}"
        g = lambda k: _root_ba(t.get(k) or {})  # noqa: E731
        sf, sb, of, fb = g("pc_self2_vs_format"), g("pc_self2_vs_base"), g("pc_other2_vs_format"), g("pc_format_vs_base")
        ib, ob = g("pc_impersonal_vs_base"), g("pc_other2_vs_base")
        ns, nf = nll.get(f"pc_self2{sfx}") or {}, nll.get(f"pc_format{sfx}") or {}
        learned = ns.get("drop") is not None and nf.get("drop") is not None and nf["drop"] >= learn_frac * ns["drop"]
        out["per_seed"][label] = {
            "self_minus_format": sf, "self_minus_base": sb, "other_minus_format": of, "format_minus_base": fb,
            "impersonal_minus_base": ib, "other_minus_base": ob,
            "nll_self": ns, "nll_format": nf, "format_learned": bool(learned),
            "115b": bool(exceeds(sf) and exceeds(sb)),
            "115c": bool(of.get("diff") is not None and not exceeds(of)),
            "115d": bool(learned and fb.get("diff") is not None and abs(fb["diff"]) <= near),
            "115e": bool(ob.get("diff") is not None and ib.get("diff") is not None and ob["diff"] < 0 and ib["diff"] <= ob["diff"] / 2)}
    for k in ("115b", "115c", "115d", "115e"):
        out[k] = bool(out["per_seed"]) and all(v[k] for v in out["per_seed"].values())
    out["criterion_adopted"] = all(out[k] for k in ("115a", "115b", "115c", "115d"))
    out["rule"] = ("the root test under v3 against a learning no-self control, at two seeds, is the registered criterion for a built self"
                   if out["criterion_adopted"] else
                   "the structural instrument has no handle on an installed self: the criterion for Act I moves to behavior, and no "
                   "further positive-control rounds run on the structural instrument")
    return out


