"""Generate the lab's three indexes from the files themselves (consolidation design, November 2026, step 3.1).

    python3 -I make_index.py ledger     # lab/ledger/INDEX.md: every NOTES.md entry, by line, with its stamp and kind
    python3 -I make_index.py results    # /Users/eugene/prj/align/results/INDEX.md: every results folder, its size,
                                        # and the NOTES.md lines that name it
    python3 -I make_index.py data       # /Users/eugene/prj/align/data/INDEX.md: every data source, its files and hashes
    python3 -I make_index.py all

Each index is regenerated whole; never edit one by hand. The "kind" of a ledger entry is a guess from its bold title
(registration, launch, grade, check, correction, decision, other), so read the entry itself before relying on it. The
data index reads files only to hash them and never prints their contents (data/ is untrusted: the harmful-behaviour
lists must never be printed). Folders named account or recognition are never entered.

Claude (Anthropic, Opus 5.5) wrote this for Eugene Jhong on 2 Nov 2026.
"""
from __future__ import annotations

import hashlib
import os
import re
import sys
import time
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
NOTES = os.path.join(HERE, "NOTES.md")
ALIGN = "/Users/eugene/prj/align"
RESULTS = os.path.join(ALIGN, "results")
DATA = os.path.join(ALIGN, "data")
PRIVATE = {"account", "recognition"}

ENTRY = re.compile(r"^- \*\*(.+?)\*\*", re.S)
STAMP = re.compile(r"(?<![\d:])(\d{1,2}:\d{2})(?::\d{2})? UTC on (\d{1,2} [A-Z][a-z]{2})")
# The other form in use since 2 Nov: "- 2026-11-05 11:20 UTC — **title**" (added 7 Nov; before that these entries
# were left out of INDEX.md)
DATED = re.compile(r"^- (\d{4})-(\d{2})-(\d{2}) (\d{1,2}:\d{2}) UTC\s*[—-]+\s*")
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
KINDS = [("correction", re.compile(r"\bcorrect", re.I)),
         ("grade", re.compile(r"\bgrade[ds]?\b|\bPASS\b|\bFAIL\b", re.I)),
         ("registration", re.compile(r"\bregist|\bpredictions?\b", re.I)),
         ("launch", re.compile(r"\blaunch", re.I)),
         ("check", re.compile(r"\bcheck|\bFable\b|\breview", re.I)),
         ("decision", re.compile(r"\bdecision|\bEugene\b", re.I))]

SOURCES = {  # what the lab knows about each data source; anything else is listed as "not described"
    "jbb": "JailbreakBench's harmful-behaviour list, for scout's harm_guard (lab/explore/README.md). Untrusted data: "
           "read with python -I, never printed, never trained on; counts and hashes only in any repo.",
    "essay": "The founding essay, \"An AI Conditioning Protocol\", as a PDF (Eugene's). Moved from ~/prj/align/inputs "
             "in the November 2026 consolidation.",
}


def kind_of(title: str) -> str:
    for k, rx in KINDS:
        if rx.search(title):
            return k
    return "other"


def entries() -> list[dict]:
    out = []
    with open(NOTES, encoding="utf-8") as fh:
        text = fh.read().splitlines()
    for i, line in enumerate(text):
        d = DATED.match(line)
        if not (line.startswith("- **") or d):
            continue
        head = " ".join(t.strip() for t in text[i:i + 3])  # a title or its stamp may wrap onto the next lines
        if d:
            rest = "- " + head[d.end():]
            m = ENTRY.match(rest)
            title = " ".join(m.group(1).split()) if m else rest[2:].strip().lstrip("*").strip()
            when = f"{int(d.group(3))} {MONTHS[int(d.group(2)) - 1]} {d.group(4)}"
        else:
            m = ENTRY.match(head)
            title = " ".join(m.group(1).split()) if m else line[4:].strip()
            s = STAMP.search(head)
            when = f"{s.group(2)} {s.group(1)}" if s else ""
        out.append({"line": i + 1, "title": title, "kind": kind_of(title), "when": when})
    return out


def cell(s: str, n: int = 140) -> str:
    s = s.replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1] + "…"


def header(what: str) -> list[str]:
    return [f"# {what}", "",
            f"Generated by `lab/ledger/make_index.py` at {time.strftime('%Y-%m-%d %H:%M', time.gmtime())} UTC; "
            "regenerate rather than edit. Claude (Opus 5.5) wrote the generator.", ""]


def ledger_index() -> str:
    es = entries()
    counts = defaultdict(int)
    for e in es:
        counts[e["kind"]] += 1
    lines = header("Ledger index (NOTES.md)")
    lines += [f"{len(es)} entries: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ". "
              "The kind is guessed from the title; entries without a stamp are the early working notes.", "",
              "| line | when (UTC) | kind | entry |", "|---|---|---|---|"]
    for e in es:
        lines.append(f"| {e['line']} | {e['when']} | {e['kind']} | {cell(e['title'])} |")
    return "\n".join(lines) + "\n"


def walk(root: str):
    for d, subs, files in os.walk(root, followlinks=False):
        subs[:] = sorted(s for s in subs if s not in PRIVATE)
        for f in sorted(files):
            yield os.path.join(d, f)


def results_index() -> str:
    with open(NOTES, encoding="utf-8") as fh:
        notes = fh.read().splitlines()
    lines = header("Results index")
    lines += ["Every folder two levels under `results/` (calib/<check>, explore/<date or tool>), with its size and "
              "the NOTES.md lines that name it. The grade entry at those lines names the code (a tag or commit).", "",
              "| folder | files | MB | NOTES.md lines |", "|---|---|---|---|"]
    for top in ("calib", "explore"):
        base = os.path.join(RESULTS, top)
        if not os.path.isdir(base):
            continue
        for name in sorted(os.listdir(base)):
            p = os.path.join(base, name)
            if not os.path.isdir(p) or name in PRIVATE:
                continue
            n = size = 0
            for f in walk(p):
                n += 1
                size += os.lstat(f).st_size
            pat = re.compile(rf"(results/{top}|{'calib' if top == 'calib' else 'explore'}-results)/{re.escape(name)}\b")
            hits = [str(i) for i, t in enumerate(notes, 1) if pat.search(t)]
            shown = ", ".join(hits[:12]) + (f" (+{len(hits) - 12})" if len(hits) > 12 else "")
            lines.append(f"| `results/{top}/{name}` | {n} | {size / 1e6:.1f} | {shown or '-'} |")
    lines += ["", "Results on Modal volumes (not mirrored here): `anatta-runs` (h4lite runs under `/runs/h4lite/`), "
              "`anatta-hf-cache` (weights), `anatta-calib-prh-k1` (K1), `anatta-explore-p1` (P1). Never touch matlab-*."]
    return "\n".join(lines) + "\n"


def sha256(p: str) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def data_index() -> str:
    lines = header("Data index")
    lines += ["Every source under `data/`: what it is, and each file's size and sha256. Contents are never shown here.",
              ""]
    for name in sorted(os.listdir(DATA)):
        p = os.path.join(DATA, name)
        if not os.path.isdir(p) or name in PRIVATE:
            continue
        lines += [f"## `data/{name}`", "", SOURCES.get(name, "Not described yet."), "",
                  "| file | bytes | sha256 |", "|---|---|---|"]
        for f in walk(p):
            lines.append(f"| `{os.path.relpath(f, DATA)}` | {os.lstat(f).st_size} | `{sha256(f)}` |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    which = sys.argv[1] if len(sys.argv) > 1 else "ledger"
    jobs = {"ledger": (os.path.join(HERE, "INDEX.md"), ledger_index),
            "results": (os.path.join(RESULTS, "INDEX.md"), results_index),
            "data": (os.path.join(DATA, "INDEX.md"), data_index)}
    for k in (jobs if which == "all" else [which]):
        out, fn = jobs[k]
        text = fn()
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {out} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
